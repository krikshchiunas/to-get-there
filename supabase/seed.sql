/* ── time helpers (session only) ────────────────────────────────────── */

-- lib/mock/time.ts → at(dayOffset, hh, mm)
create or replace function pg_temp.day_at(day_offset integer, hh integer, mm integer default 0)
returns timestamptz
language sql
as $$
  select ((current_date + day_offset) + make_time(hh, mm, 0))::timestamptz;
$$;

-- lib/mock/time.ts → nextWeekday(weekday, hh, mm): the next Monday(1) …
-- Sunday(7), today excluded.
create or replace function pg_temp.weekday_at(iso_weekday integer, hh integer, mm integer default 0)
returns timestamptz
language sql
as $$
  select ((current_date
            + (((iso_weekday - extract(isodow from current_date)::integer + 6) % 7) + 1))
          + make_time(hh, mm, 0))::timestamptz;
$$;

